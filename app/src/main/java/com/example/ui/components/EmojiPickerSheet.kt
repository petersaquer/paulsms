@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EmojiPickerSheet(
    onDismiss: () -> Unit,
    onEmojiSelected: (String) -> Unit
) {
    var selectedTabIndex by remember { mutableIntStateOf(0) }
    val categories = listOf(
        EmojiCategory("Caras", "😀", EmojiData.SMILEYS),
        EmojiCategory("Personas", "👋", EmojiData.PEOPLE),
        EmojiCategory("Animales", "🐶", EmojiData.ANIMALS),
        EmojiCategory("Comida", "🍎", EmojiData.FOOD),
        EmojiCategory("Actividades", "⚽", EmojiData.ACTIVITIES),
        EmojiCategory("Viajes", "🚗", EmojiData.TRAVEL),
        EmojiCategory("Objetos", "💡", EmojiData.OBJECTS),
        EmojiCategory("Símbolos", "❤️", EmojiData.SYMBOLS)
    )

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        shape = RoundedCornerShape(topStart = 24.dp, topEnd = 24.dp),
        containerColor = MaterialTheme.colorScheme.surface,
        dragHandle = {
            Column(horizontalAlignment = Alignment.CenterHorizontally, modifier = Modifier.fillMaxWidth().padding(vertical = 8.dp)) {
                Box(modifier = Modifier.width(36.dp).height(4.dp).clip(CircleShape).background(MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.4f)))
            }
        }
    ) {
        Column(modifier = Modifier.fillMaxWidth().height(450.dp)) {
            TabRow(
                selectedTabIndex = selectedTabIndex,
                containerColor = Color.Transparent,
                contentColor = TelegramAccent,
                indicator = { tabPositions ->
                    TabRowDefaults.SecondaryIndicator(
                        modifier = Modifier.tabIndicatorOffset(tabPositions[selectedTabIndex]),
                        color = TelegramAccent
                    )
                },
                divider = {}
            ) {
                categories.forEachIndexed { index, category ->
                    Tab(
                        selected = selectedTabIndex == index,
                        onClick = { selectedTabIndex = index },
                        text = { Text(category.icon, fontSize = 20.sp) }
                    )
                }
            }

            val currentEmojis = categories[selectedTabIndex].emojis
            LazyVerticalGrid(
                columns = GridCells.Adaptive(minSize = 48.dp),
                contentPadding = PaddingValues(12.dp),
                horizontalArrangement = Arrangement.spacedBy(4.dp),
                verticalArrangement = Arrangement.spacedBy(4.dp),
                modifier = Modifier.weight(1f)
            ) {
                items(currentEmojis) { emoji ->
                    Box(
                        modifier = Modifier
                            .size(48.dp)
                            .clip(RoundedCornerShape(8.dp))
                            .clickable { onEmojiSelected(emoji) },
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = emoji,
                            fontSize = 30.sp,
                            textAlign = TextAlign.Center
                        )
                    }
                }
            }
            
            // Bottom Action Bar like WhatsApp (could add backspace here)
            Row(
                modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 8.dp),
                horizontalArrangement = Arrangement.End
            ) {
                TextButton(onClick = onDismiss) {
                    Text("Cerrar", color = TelegramAccent, fontWeight = FontWeight.Bold)
                }
            }
        }
    }
}

